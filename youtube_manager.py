def add_unique_songs(yt_client, playlist_id, new_song_ids):
    """
    Helper function: Only adds songs that are NOT already in the playlist.
    """
    try:
        # 1. Get current songs in the target playlist
        playlist_data = yt_client.get_playlist(playlist_id, limit=None)
        existing_tracks = playlist_data.get('tracks', [])
        
        # Create a set of existing Video IDs for fast checking
        existing_ids = set(track['videoId'] for track in existing_tracks)
        
        # 2. Filter out duplicates
        unique_ids_to_add = [vid for vid in new_song_ids if vid not in existing_ids]
        
        if not unique_ids_to_add:
            print("   -> No new songs to add (all duplicates).")
            return

        # 3. Add only the new ones
        yt_client.add_playlist_items(playlist_id, unique_ids_to_add)
        print(f"   -> Added {len(unique_ids_to_add)} new songs.")
        
    except Exception as e:
        print(f"   -> Error syncing playlist: {e}")

def create_playlists(yt_client, playlist_data):
    """
    Main entry point.
    Input: { "AI Vibe: Rock": ['id1', 'id2'], ... }
    """
    print("\nSTARTING YOUTUBE SYNC...")
    
    # Get existing playlists once (to check for duplicates)
    try:
        my_playlists = yt_client.get_library_playlists(limit=50)
        existing_names = {p['title']: p['playlistId'] for p in my_playlists}
    except Exception as e:
        print(f"Error fetching existing playlists: {e}")
        return
    
    # Iterate through the dictionary from main.py
    for name, song_ids in playlist_data.items():
        print(f"Processing '{name}' ({len(song_ids)} songs)...")
        
        playlist_id = existing_names.get(name)
        
        # Create if doesn't exist
        if not playlist_id:
            print(f"   -> Creating new playlist: {name}")
            try:
                playlist_id = yt_client.create_playlist(title=name, description="Generated by AI Music Manager")
            except Exception as e:
                print(f"   ->Error creating playlist: {e}")
                continue
        else:
            print(f"   -> Found existing playlist (ID: {playlist_id})")
            
        # Call the helper function to add songs safely
        add_unique_songs(yt_client, playlist_id, song_ids)